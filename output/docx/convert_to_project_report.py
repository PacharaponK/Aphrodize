CAPTION_REPLACEMENTS = {
    "รูปที่ 10 หน้าวิเคราะห์ภาพใน Progress 2": "รูปที่ 10 หน้าจอเตรียมและวิเคราะห์ภาพ",
    "รูปที่ 11 หน้าผลวิเคราะห์ใบหน้าใน Progress 3": "รูปที่ 11 หน้าผลการวิเคราะห์ใบหน้า",
}


def main() -> None:
    document = Document(REPORT)
    seen: set[str] = set()
    for paragraph in document.paragraphs:
        old = paragraph.text.strip()
        if old in REPLACEMENTS:
            paragraph.text = REPLACEMENTS[old]
            seen.add(old)
        elif "\t" in paragraph.text:
            label, page = paragraph.text.split("\t", 1)
            label = label.strip()
            if label in CAPTION_REPLACEMENTS:
                paragraph.text = f"{CAPTION_REPLACEMENTS[label]}\t{page}"
                seen.add(label)
        elif old in CAPTION_REPLACEMENTS:
            paragraph.text = CAPTION_REPLACEMENTS[old]
            seen.add(old)

    available_text = {paragraph.text.strip() for paragraph in document.paragraphs}
    expected = set(REPLACEMENTS) | set(CAPTION_REPLACEMENTS)
    missing = {
        source for source in expected
        if source not in seen and REPLACEMENTS.get(source, CAPTION_REPLACEMENTS.get(source)) not in available_text
    }
    if missing:
        raise SystemExit(f"Expected source text not found: {sorted(missing)}")

    for table in document.tables:
        for row in table.rows:
            for cell in row.cells:
                if cell.text.strip() in {"Progress 2 tests", "การทดสอบวิเคราะห์ภาพ"}:
                    cell.paragraphs[0].text = "ทดสอบภาพ"

    document.core_properties.title = "รายงานโครงงาน Aphrodize"
    document.save(REPORT)
    print(f"Reframed report as a whole-project report: {REPORT}")


if __name__ == "__main__":
    main()
